type Props = {
  name: IconName
  size?: number | string
  className?: string
  style?: CSSProperties
  title?: string
  strokeWidth?: number
} & Omit<SVGProps<SVGSVGElement>, 'name' | 'ref'>

export function Icon({
  name,
  size = 16,
  className = '',
  style,
  title,
  strokeWidth = 1.75,
  ...rest
}: Props) {
  const body = paths[name]
  if (!body) return null
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`${styles.icon} ${className}`.trim()}
      style={style}
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      {body}
    </svg>
  )
}

/** 아이콘 + 텍스트 인라인 래퍼 */
export function IconLabel({
  name,
  children,
  size = 14,
  gap = 6,
  className = '',
}: {
  name: IconName
  children?: ReactNode
  size?: number
  gap?: number
  className?: string
}) {
  return (
    <span className={`${styles.label} ${className}`.trim()} style={{ gap }}>
      <Icon name={name} size={size} />
      {children != null ? <span>{children}</span> : null}
    </span>
  )
}
